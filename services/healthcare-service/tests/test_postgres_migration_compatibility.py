def _database_url() -> str:
    database_url = os.getenv("HEALTHCARE_MIGRATION_TEST_DATABASE_URL")
    if not database_url:
        pytest.skip("HEALTHCARE_MIGRATION_TEST_DATABASE_URL is not configured")
    return database_url


def _quote_identifier(value: str) -> str:
    return '"' + value.replace('"', '""') + '"'


def _schema_database_url(database_url: str, schema: str) -> str:
    parsed = urlsplit(database_url)
    query = parse_qsl(parsed.query, keep_blank_values=True)
    query.append(("options", f"-c search_path={schema},public"))
    return urlunsplit((parsed.scheme, parsed.netloc, parsed.path, urlencode(query), parsed.fragment))


@pytest.fixture
def schema_factory():
    database_url = _database_url()
    schemas: list[str] = []

    def create_schema() -> str:
        schema = f"healthcare_migration_{uuid4().hex}"
        with psycopg.connect(database_url, autocommit=True) as connection:
            connection.execute(f"CREATE SCHEMA {_quote_identifier(schema)}")
        schemas.append(schema)
        return schema

    try:
        yield create_schema
    finally:
        with psycopg.connect(database_url, autocommit=True) as connection:
            for schema in schemas:
                connection.execute(f"DROP SCHEMA IF EXISTS {_quote_identifier(schema)} CASCADE")


def _apply_sql(database_url: str, schema: str, sql: str) -> None:
    with psycopg.connect(database_url, autocommit=True) as connection:
        connection.execute(f"SET search_path TO {_quote_identifier(schema)}, public")
        connection.execute(sql)


def _apply_file(database_url: str, schema: str, path: Path) -> None:
    _apply_sql(database_url, schema, path.read_text(encoding="utf-8"))


def _apply_current(database_url: str, schema: str, names: tuple[str, ...]) -> None:
    for name in names:
        _apply_file(database_url, schema, MIGRATIONS / name)


def _seed_legacy_rows(database_url: str, schema: str) -> dict[str, int | str]:
    with psycopg.connect(database_url, autocommit=True) as connection:
        connection.execute(f"SET search_path TO {_quote_identifier(schema)}, public")
        facility_id = connection.execute(
            "INSERT INTO healthcare_facilities (source_id, name, address, city) VALUES ('legacy-facility-001', 'Legacy Clinic', 'Existing address', 'Ha Noi') RETURNING id"
        ).fetchone()[0]
        second_facility_id = connection.execute(
            "INSERT INTO healthcare_facilities (source_id, name, address) VALUES ('legacy-facility-002', 'Second Legacy Clinic', 'Second address') RETURNING id"
        ).fetchone()[0]
        department_id = connection.execute(
            "INSERT INTO departments (name, description, source_id, facility_id) VALUES ('Legacy Cardiology', 'Existing department', 'legacy-department-001', %s) RETURNING id",
            (facility_id,),
        ).fetchone()[0]
        connection.execute(
            "INSERT INTO departments (name, description, source_id, facility_id) VALUES ('Legacy Cardiology', 'Same name at another facility', 'legacy-department-002', %s)",
            (second_facility_id,),
        )
        doctor_id = connection.execute(
            "INSERT INTO doctors (department_id, name, price, description, source_id, facility_id) VALUES (%s, 'Legacy Doctor', 250000, 'Existing doctor', 'legacy-doctor-001', %s) RETURNING id",
            (department_id, facility_id),
        ).fetchone()[0]
        patient_id = connection.execute(
            "INSERT INTO patients (name, phone) VALUES ('Legacy Patient', '0900000000') RETURNING id"
        ).fetchone()[0]
        slot_id = connection.execute(
            "INSERT INTO time_slots (doctor_id, start_time, end_time, status) VALUES (%s, CURRENT_TIMESTAMP + INTERVAL '1 day', CURRENT_TIMESTAMP + INTERVAL '1 day 30 minutes', 'HOLDING') RETURNING id",
            (doctor_id,),
        ).fetchone()[0]
        appointment_id = connection.execute(
            "INSERT INTO appointments (actor_id, patient_id, doctor_id, slot_id, status, is_paid) VALUES ('legacy-actor', %s, %s, %s, 'DRAFT', FALSE) RETURNING id",
            (patient_id, doctor_id, slot_id),
        ).fetchone()[0]
    return {
        "facility_id": facility_id,
        "facility_source_id": "legacy-facility-001",
        "department_id": department_id,
        "doctor_id": doctor_id,
        "patient_id": patient_id,
        "slot_id": slot_id,
        "appointment_id": appointment_id,
    }


def _columns(database_url: str, schema: str, table: str) -> set[str]:
    with psycopg.connect(database_url, autocommit=True) as connection:
        connection.execute(f"SET search_path TO {_quote_identifier(schema)}, public")
        rows = connection.execute(
            "SELECT column_name FROM information_schema.columns WHERE table_schema = current_schema() AND table_name = %s",
            (table,),
        ).fetchall()
    return {row[0] for row in rows}


def test_fresh_healthcare_migration_path_and_bridge_noop(schema_factory) -> None:
    database_url = _database_url()
    schema = schema_factory()
    _apply_current(database_url, schema, ("001_healthcare_booking.sql", "002_healthcare_slot_reuse.sql", "003_patient_user_links.sql"))

    with psycopg.connect(database_url, autocommit=True) as connection:
        connection.execute(f"SET search_path TO {_quote_identifier(schema)}, public")
        assert connection.execute("SELECT to_regclass('healthcare_facilities')").fetchone()[0] is None

    _apply_file(database_url, schema, BRIDGE)
    with psycopg.connect(database_url, autocommit=True) as connection:
        connection.execute(f"SET search_path TO {_quote_identifier(schema)}, public")
        assert connection.execute("SELECT to_regclass('healthcare_facilities')").fetchone()[0] is None

    _apply_current(database_url, schema, ("004_healthcare_catalog_provenance.sql", "005_healthcare_catalog_nullable_price.sql"))
    _apply_file(database_url, schema, BRIDGE)
    _apply_current(database_url, schema, ("004_healthcare_catalog_provenance.sql", "005_healthcare_catalog_nullable_price.sql"))

    assert {"source_id", "last_verified_at", "dataset_version", "content_hash", "is_active", "provenance_json"}.issubset(_columns(database_url, schema, "healthcare_facilities"))
    assert "id" not in _columns(database_url, schema, "healthcare_facilities")
    assert _columns(database_url, schema, "patient_user_links")


def test_legacy_healthcare_catalog_upgrades_without_data_loss(schema_factory) -> None:
    database_url = _database_url()
    schema = schema_factory()
    _apply_current(database_url, schema, ("001_healthcare_booking.sql", "002_healthcare_slot_reuse.sql"))
    _apply_sql(database_url, schema, LEGACY_003_SQL)
    legacy = _seed_legacy_rows(database_url, schema)

    _apply_file(database_url, schema, MIGRATIONS / "003_patient_user_links.sql")
    _apply_file(database_url, schema, BRIDGE)
    _apply_file(database_url, schema, BRIDGE)
    _apply_current(database_url, schema, ("004_healthcare_catalog_provenance.sql", "005_healthcare_catalog_nullable_price.sql"))

    assert {"id", "source_id", "last_verified_at", "dataset_version", "content_hash", "is_active", "provenance_json"}.issubset(_columns(database_url, schema, "healthcare_facilities"))
    assert {"facility_id", "facility_source_id", "dataset_version", "provenance_json"}.issubset(_columns(database_url, schema, "departments"))
    assert {"facility_id", "facility_source_id", "dataset_version", "provenance_json"}.issubset(_columns(database_url, schema, "doctors"))

    with psycopg.connect(database_url, autocommit=True) as connection:
        connection.execute(f"SET search_path TO {_quote_identifier(schema)}, public")
        assert connection.execute("SELECT id FROM healthcare_facilities WHERE source_id = 'legacy-facility-001'").fetchone()[0] == legacy["facility_id"]
        assert connection.execute("SELECT facility_source_id FROM departments WHERE source_id = 'legacy-department-001'").fetchone()[0] == legacy["facility_source_id"]
        assert connection.execute("SELECT facility_source_id FROM doctors WHERE source_id = 'legacy-doctor-001'").fetchone()[0] == legacy["facility_source_id"]
        assert connection.execute("SELECT COUNT(*) FROM departments WHERE name = 'Legacy Cardiology'").fetchone()[0] == 2

        connection.execute(
            "INSERT INTO patient_user_links (actor_user_id, patient_id, relationship, is_default) VALUES ('legacy-actor', %s, 'self', TRUE)",
            (legacy["patient_id"],),
        )
        assert connection.execute("SELECT patient_id FROM patient_user_links WHERE actor_user_id = 'legacy-actor'").fetchone()[0] == legacy["patient_id"]
        connection.execute("UPDATE appointments SET status = 'CANCELLED' WHERE id = %s", (legacy["appointment_id"],))
        replacement_id = connection.execute(
            "INSERT INTO appointments (actor_id, patient_id, doctor_id, slot_id, status, is_paid) VALUES ('replacement-actor', %s, %s, %s, 'DRAFT', FALSE) RETURNING id",
            (legacy["patient_id"], legacy["doctor_id"], legacy["slot_id"]),
        ).fetchone()[0]
        assert replacement_id != legacy["appointment_id"]

    engine = create_engine(sqlalchemy_database_url(_schema_database_url(database_url, schema)))
    with engine.connect() as connection:
        with Session(bind=connection) as db:
            facility = db.get(HealthcareFacility, legacy["facility_source_id"])
            assert facility is not None
            assert facility.name == "Legacy Clinic"
            assert _facility_data(db, str(legacy["facility_source_id"]))["source_id"] == legacy["facility_source_id"]
    engine.dispose()

    plan = build_plan("healthcare", f"migration-compat-{uuid4().hex[:12]}")
    asyncio.run(apply_plan(plan, _schema_database_url(database_url, schema), allow_rejected=False))

    with psycopg.connect(database_url, autocommit=True) as connection:
        connection.execute(f"SET search_path TO {_quote_identifier(schema)}, public")
        assert connection.execute("SELECT COUNT(*) FROM healthcare_facilities WHERE source_id = 'legacy-facility-001'").fetchone()[0] == 1
        assert connection.execute("SELECT COUNT(*) FROM departments WHERE source_id = 'legacy-department-001'").fetchone()[0] == 1
        assert connection.execute("SELECT COUNT(*) FROM doctors WHERE source_id = 'legacy-doctor-001'").fetchone()[0] == 1
        assert connection.execute("SELECT COUNT(*) FROM catalog_dataset_versions WHERE domain = 'healthcare'").fetchone()[0] == 1
