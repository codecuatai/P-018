-- Healthcare-owned schema. Apply explicitly before running the deterministic seed.
CREATE TABLE IF NOT EXISTS departments (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR(255) NOT NULL UNIQUE,
  description TEXT
);

CREATE INDEX IF NOT EXISTS ix_departments_name ON departments (name);

CREATE TABLE IF NOT EXISTS doctors (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  department_id INTEGER NOT NULL REFERENCES departments(id),
  name VARCHAR(255) NOT NULL,
  price INTEGER NOT NULL CHECK (price >= 0),
  description TEXT
);

CREATE INDEX IF NOT EXISTS ix_doctors_department_id ON doctors (department_id);

CREATE TABLE IF NOT EXISTS patients (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR(255) NOT NULL,
  phone VARCHAR(64) NOT NULL,
  blood_type VARCHAR(16),
  medical_history TEXT
);

CREATE TABLE IF NOT EXISTS time_slots (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  doctor_id INTEGER NOT NULL REFERENCES doctors(id),
  start_time TIMESTAMP NOT NULL,
  end_time TIMESTAMP NOT NULL,
  status VARCHAR(16) NOT NULL CHECK (status IN ('AVAILABLE', 'HOLDING', 'BOOKED')),
  hold_expires_at TIMESTAMP
);

CREATE INDEX IF NOT EXISTS ix_time_slots_doctor_id ON time_slots (doctor_id);
CREATE INDEX IF NOT EXISTS ix_time_slots_status ON time_slots (status);

CREATE TABLE IF NOT EXISTS appointments (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  actor_id VARCHAR(128) NOT NULL,
  patient_id INTEGER NOT NULL REFERENCES patients(id),
  symptoms TEXT,
  doctor_id INTEGER NOT NULL REFERENCES doctors(id),
  slot_id INTEGER NOT NULL UNIQUE REFERENCES time_slots(id),
  status VARCHAR(16) NOT NULL CHECK (status IN ('DRAFT', 'CONFIRMED', 'CANCELLED')),
  is_paid BOOLEAN NOT NULL DEFAULT FALSE,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS ix_appointments_actor_id ON appointments (actor_id);

CREATE TABLE IF NOT EXISTS audit_logs (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  appointment_id INTEGER NOT NULL REFERENCES appointments(id),
  action VARCHAR(80) NOT NULL,
  timestamp TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  details TEXT
);

CREATE TABLE IF NOT EXISTS idempotency_records (
  idempotency_key VARCHAR(255) PRIMARY KEY,
  actor_id VARCHAR(128) NOT NULL,
  operation VARCHAR(80) NOT NULL,
  request_hash VARCHAR(64) NOT NULL,
  response_body TEXT NOT NULL,
  status_code INTEGER NOT NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
