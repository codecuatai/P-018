-- Additive Healthcare provider catalog imported from the owned CSV sources.
-- Existing appointments, patients, holds, and departments remain intact.

BEGIN;

CREATE TABLE IF NOT EXISTS healthcare_facilities (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  source_id VARCHAR(255) NOT NULL UNIQUE,
  name VARCHAR(255) NOT NULL,
  facility_type VARCHAR(80),
  address VARCHAR(500),
  ward VARCHAR(255),
  district VARCHAR(255),
  city VARCHAR(255),
  latitude DOUBLE PRECISION,
  longitude DOUBLE PRECISION,
  phone VARCHAR(64),
  website VARCHAR(500),
  description TEXT,
  emergency_available BOOLEAN,
  opening_hours VARCHAR(255),
  image_url VARCHAR(500),
  source_name VARCHAR(255),
  source_url VARCHAR(500),
  fetched_at TIMESTAMP
);

ALTER TABLE departments ADD COLUMN IF NOT EXISTS source_id VARCHAR(255);
ALTER TABLE departments ADD COLUMN IF NOT EXISTS facility_id INTEGER REFERENCES healthcare_facilities(id);

ALTER TABLE departments DROP CONSTRAINT IF EXISTS departments_name_key;
CREATE UNIQUE INDEX IF NOT EXISTS uq_departments_facility_name
  ON departments (facility_id, name)
  WHERE facility_id IS NOT NULL;
CREATE UNIQUE INDEX IF NOT EXISTS uq_departments_facility_source
  ON departments (facility_id, source_id)
  WHERE facility_id IS NOT NULL AND source_id IS NOT NULL;
CREATE INDEX IF NOT EXISTS ix_departments_facility_id ON departments (facility_id);

ALTER TABLE doctors ADD COLUMN IF NOT EXISTS source_id VARCHAR(255);
ALTER TABLE doctors ADD COLUMN IF NOT EXISTS facility_id INTEGER REFERENCES healthcare_facilities(id);
ALTER TABLE doctors ADD COLUMN IF NOT EXISTS title VARCHAR(80);
ALTER TABLE doctors ADD COLUMN IF NOT EXISTS specialty VARCHAR(120);
ALTER TABLE doctors ADD COLUMN IF NOT EXISTS image_url VARCHAR(500);
ALTER TABLE doctors ADD COLUMN IF NOT EXISTS source_url VARCHAR(500);
ALTER TABLE doctors ALTER COLUMN price DROP NOT NULL;

CREATE UNIQUE INDEX IF NOT EXISTS uq_doctors_source_id
  ON doctors (source_id)
  WHERE source_id IS NOT NULL;
CREATE INDEX IF NOT EXISTS ix_doctors_facility_id ON doctors (facility_id);

COMMIT;
