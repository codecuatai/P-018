-- Healthcare-owned patient identity links. Core owns the user identity; this
-- service owns the medical patient record and relationship semantics.
CREATE TABLE IF NOT EXISTS patient_user_links (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  actor_user_id VARCHAR(128) NOT NULL,
  patient_id INTEGER NOT NULL REFERENCES patients(id),
  relationship VARCHAR(24) NOT NULL CHECK (relationship IN ('self', 'child', 'parent', 'dependent')),
  is_default BOOLEAN NOT NULL DEFAULT FALSE,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT uq_patient_user_links_actor_patient UNIQUE (actor_user_id, patient_id)
);

CREATE INDEX IF NOT EXISTS ix_patient_user_links_actor_user_id ON patient_user_links (actor_user_id);

CREATE UNIQUE INDEX IF NOT EXISTS uq_patient_user_links_one_default
  ON patient_user_links (actor_user_id)
  WHERE is_default = TRUE;
